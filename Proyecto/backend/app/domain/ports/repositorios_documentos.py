"""Puertos de repositorios del mapa de datos, los informes RoPA, la plataforma y los borradores (A-12).

Las entidades que cruzan son modelos del dominio (`Any`). Ningún método confirma: la transacción
(commit/rollback/flush) es del caso de uso, que sigue recibiendo la `AsyncSession` como unidad de trabajo.
"""
from __future__ import annotations

from datetime import datetime
from typing import Any, Protocol


class MapaDatosRepositoryPort(Protocol):
    """Consultas y escrituras del mapa de datos (HU-34)."""

    async def mapa(self, empresa_id: int, *, bloquear: bool = False) -> Any | None: ...

    async def elementos(self, mapa_id: int) -> list: ...

    async def flujos(self, mapa_id: int) -> list: ...

    async def nombre_rubro(self, rubro_id: int) -> str | None: ...

    async def versiones_recientes(self, mapa_id: int, cuantos: int) -> list[tuple]:
        """(numero, fecha, resumen) de las últimas versiones, de la más nueva a la más antigua."""
        ...

    async def contar_versiones(self, mapa_id: int) -> int: ...

    async def pagina_de_versiones(self, mapa_id: int, desplazamiento: int, limite: int) -> list: ...

    async def version(self, mapa_id: int, numero: int) -> Any | None: ...

    async def respuestas_filtro(self, evaluacion_id: int) -> list[tuple]:
        """(código de la pregunta del filtro, respuesta) de una evaluación."""
        ...

    def agregar(self, entidad: Any) -> None:
        """Registra una entidad nueva en la unidad de trabajo."""
        ...

    def agregar_varios(self, entidades: list) -> None: ...

    async def eliminar(self, entidad: Any) -> None: ...

    async def eliminar_flujos(self, ids: list[int]) -> None: ...

    async def volcar(self) -> None:
        """Flush; traduce la violación de integridad a `ConflictoIntegridadError` (sin rollback)."""
        ...


class InformeRopaRepositoryPort(Protocol):
    """Consultas y escrituras del informe RoPA de la empresa (HU-37)."""

    async def datos(self, empresa_id: int) -> Any | None: ...

    async def ultima_emision(self, empresa_id: int) -> Any | None: ...

    async def emisiones_recientes(self, empresa_id: int, limite: int) -> list: ...

    async def contar_desde(self, empresa_id: int, desde: datetime) -> int: ...

    async def documento(self, documento_id: int) -> Any | None: ...

    async def emision(self, informe_id: int) -> Any | None: ...

    async def bloquear_empresa(self, empresa_id: int) -> None:
        """Serializa las emisiones de la empresa (SELECT ... FOR UPDATE)."""
        ...

    def agregar(self, entidad: Any) -> None: ...

    async def refrescar(self, entidad: Any) -> None: ...


class PlataformaRepositoryPort(Protocol):
    """Consultas y escrituras de los informes de privacidad de la plataforma (HU-41)."""

    async def datos(self) -> Any | None: ...

    async def ultima_emision(self, tipo: str) -> Any | None: ...

    async def emisiones_recientes(self, limite: int) -> list: ...

    async def contar_desde(self, desde: datetime) -> int: ...

    async def emision(self, informe_id: int) -> Any | None: ...

    def agregar(self, entidad: Any) -> None: ...

    async def refrescar(self, entidad: Any) -> None: ...


class BorradoresRepositoryPort(Protocol):
    """Consultas y escrituras de los borradores de documentos (HU-16)."""

    async def borrador(self, borrador_id: int) -> Any | None: ...

    async def listar(self, empresa_id: int) -> list: ...

    async def contar_en_revision(self, empresa_id: int) -> int: ...

    async def fuentes_de_controles(self, codigos: list[str]) -> list[tuple]:
        """(código, framework, artículo) de los controles de la matriz."""
        ...

    async def rubro(self, rubro_id: int) -> Any | None: ...

    def agregar(self, entidad: Any) -> None: ...

    async def eliminar(self, entidad: Any) -> None: ...
