"""Puertos de repositorios usados por los casos de uso (solo los métodos que application necesita)."""
from __future__ import annotations

from datetime import datetime
from typing import Any, Protocol


class RespuestaDuplicadaError(Exception):
    """Ya existe una respuesta para ese (evaluación, control): la insertó otra
    petición concurrente entre la búsqueda y el INSERT."""


class EvaluacionRepositoryPort(Protocol):
    session: Any

    async def get(self, evaluacion_id: int) -> Any | None: ...

    async def get_contexto(self, evaluacion_id: int) -> Any | None: ...

    async def update(self, evaluacion: Any) -> Any: ...


class RespuestaRepositoryPort(Protocol):
    async def create(self, respuesta: Any) -> Any: ...

    async def get(self, respuesta_id: int) -> Any | None: ...

    async def get_by_evaluacion_control(self, evaluacion_id: int, control_id: int) -> Any | None: ...

    async def list_estado_por_evaluacion(self, evaluacion_id: int) -> list: ...

    async def update(self, respuesta: Any) -> Any: ...

    async def get_control(self, control_id: int) -> Any | None: ...

    async def get_brecha(self, brecha_id: int) -> Any | None: ...


class EvidenciaRepositoryPort(Protocol):
    async def create(self, evidencia: Any) -> Any: ...

    async def get(self, evidencia_id: int) -> Any | None: ...

    async def update(self, evidencia: Any) -> Any: ...


class TutorRepositoryPort(Protocol):
    async def obtener(self, conversacion_id: int, empresa_id: int) -> Any | None: ...

    async def listar(self, empresa_id: int, limite: int = 50) -> list[Any]: ...

    async def contar(self, empresa_id: int) -> int: ...

    def agregar(self, fila: Any) -> None: ...

    async def mensajes(self, conversacion_id: int) -> list[Any]: ...

    async def historial(self, conversacion_id: int, n: int) -> list[Any]: ...

    async def eliminar(self, conversacion_id: int) -> int: ...

    async def inactivas_desde(self, limite: datetime) -> list[int]: ...

    async def eliminar_ids(self, ids: list[int]) -> int: ...


class PreguntaFiltroRepositoryPort(Protocol):
    async def list_activas(self) -> list[Any]: ...


class RespuestaFiltroRepositoryPort(Protocol):
    async def bulk_create(self, respuestas: list[Any]) -> list[Any]: ...

    async def list_by_evaluacion(self, evaluacion_id: int) -> list[Any]: ...

    async def delete_by_evaluacion(self, evaluacion_id: int) -> None: ...


class MatrizRepositoryPort(Protocol):
    async def publicada(self) -> Any | None: ...

    async def borrador(self) -> Any | None: ...

    async def obtener(self, version_id: int) -> Any | None: ...

    async def listar(self) -> list[Any]: ...

    async def evaluaciones_por_version(self) -> dict[int, int]: ...

    async def contenido_desde_tablas(self) -> dict: ...

    async def aplicar(self, contenido: dict) -> dict: ...


class AnonimizacionRepositoryPort(Protocol):
    async def anonimizar_titular(self, usuario_id: int, ahora: datetime) -> tuple[dict, list[str]]: ...

    async def anonimizar_encuestado(self, evaluacion_id: int, ahora: datetime) -> tuple[dict, list[str]]: ...
